#!/usr/bin/env node
/** Maintainer-only import from a fixed, reviewed Git tree. Never reads an AgentFS or bundles media. */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = process.argv[2];
if (!source) throw new Error('Usage: node scripts/sync-shotcraft.mjs <reviewed video-shotcraft Git checkout>');
const commit = '075b548c2405a07b77129eb448b0b504fc60dea3';
const base = 'skills/motion-graphics/references/shotcraft';
const git = (...args) => execFileSync('git', args, { cwd: source, windowsHide: true, maxBuffer: 20 * 1024 * 1024 });
const paths = git('ls-tree', '-r', '--name-only', commit).toString('utf8').trim().split('\n');
// Source-only selection from the immutable tree, materialized as an explicit seed allowlist below.
const selected = paths.filter((p) => /^references\/.*\.md$/.test(p)
  || /^(?:demos|assets\/lib)\/.*\.(?:tsx|ts)$/.test(p)
  || ['SKILL.md', 'LICENSE', 'NOTICE', 'gallery/api/library.json', 'assets/scripts/sfx-source.py', 'assets/scripts/test_sfx_source.py'].includes(p));
const write = (name, data) => { mkdirSync(dirname(resolve(root, name)), { recursive: true }); writeFileSync(resolve(root, name), data); };
const records = [];
for (const path of selected.sort()) {
  const data = git('show', `${commit}:${path}`);
  const destination = path === 'LICENSE' ? 'licenses/VideoShotcraft-Apache-2.0.txt'
    : `${base}/upstream/${path === 'SKILL.md' ? 'SKILL.original.md' : path}`;
  write(destination, data);
  records.push({ path, destination, sha256: createHash('sha256').update(data).digest('hex'), bytes: data.length });
}
const original = JSON.parse(readFileSync(resolve(root, `${base}/upstream/gallery/api/library.json`), 'utf8'));
const cards = original.cards.map((card) => {
  const doc = readFileSync(resolve(root, `${base}/upstream/${card.source}`), 'utf8');
  const mentions = [...doc.matchAll(/demos\/[\w/-]+(?:\.tsx)?/g)].map(([s]) => s.replace(/\/$/, ''));
  const demos = records.filter((r) => r.path.startsWith('demos/') && mentions.some((p) => r.path === p || r.path.startsWith(p + '/'))).map((r) => r.path);
  return { name: card.name, category: card.category, summary: card.summary, use: card.use || '', duration: card.duration || '',
    energy: card.energy || '', intention: card.intention || '', document: card.source, demos,
    styles: card.styles.map((s) => ({ key: s.key, label: s.label, description: s.description || '', use: s.use || '' })),
    nativeStatus: 'reference-only' };
});
const catalog = { $schema: './catalog.schema.json', description: 'Fixed upstream shot vocabulary. Reference availability is not proof of native execution; read the card and exact demo before adapting.',
  repository: 'https://github.com/Vincentwei1021/video-shotcraft', commit,
  counts: { cards: cards.length, styles: cards.reduce((n, c) => n + c.styles.length, 0) }, categories: original.categories, cards };
write(`${base}/catalog.json`, JSON.stringify(catalog, null, 2) + '\n');
write(`${base}/SOURCE.json`, JSON.stringify({ description: 'Exact Git blob bytes, Apache-2.0 source-only import; no preview/audio files, dependencies or executable upstream skill installation.',
  repository: catalog.repository, commit, license: 'Apache-2.0', files: records }, null, 2) + '\n');
const additions = [`${base}/README.md`, `${base}/catalog.json`, `${base}/catalog.schema.json`, `${base}/SOURCE.json`,
  'skills/motion-graphics/scripts/shotcraft.mjs', ...records.map((r) => r.destination)].sort();
write('scripts/shotcraft-files.mjs', '/** Explicit source-only Shotcraft seed list; generated by sync-shotcraft.mjs from a fixed Git tree. */\nexport const SHOTCRAFT_FILES = Object.freeze(' + JSON.stringify(additions, null, 2) + ');\n');
console.log(JSON.stringify({ commit, importedFiles: records.length, ...catalog.counts, missingDemoLocator: cards.filter((c) => !c.demos.length).map((c) => c.name) }));
